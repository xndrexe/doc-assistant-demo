def make_contract(path: Path) -> None:
    pdf = FPDF(format="A4")
    pdf.add_font("DejaVu", "", FONT)
    pdf.add_font("DejaVu", "B", FONT_BOLD)
    pdf.set_margins(20, 20, 20)
    pdf.set_auto_page_break(True, margin=20)
    pdf.add_page()
    pdf.set_font("DejaVu", "B", 14)
    pdf.multi_cell(0, 8, "Договор на ремонт бытовой техники (публичная оферта)", align="C", **NEXT_LINE)
    pdf.set_font("DejaVu", "", 10)
    pdf.multi_cell(0, 6, "г. Энск, редакция от 01.09.2026", align="C", **NEXT_LINE)
    pdf.ln(4)
    for i, (title, items) in enumerate(CONTRACT):
        # по два раздела на страницу — чтобы в ответе была видна ссылка на номер страницы
        if i and i % 2 == 0:
            pdf.add_page()
        pdf.set_font("DejaVu", "B", 12)
        pdf.multi_cell(0, 8, title, **NEXT_LINE)
        pdf.set_font("DejaVu", "", 11)
        for item in items:
            pdf.multi_cell(0, 6, item, **NEXT_LINE)
            pdf.ln(2)
        pdf.ln(3)
    pdf.output(str(path))


def make_returns(path: Path) -> None:
    doc = Document()
    (title, intro), *sections = RETURNS
    doc.add_heading(title, level=1)
    doc.add_paragraph(intro)
    for head, text in sections:
        doc.add_heading(head, level=2)
        doc.add_paragraph(text)
    doc.save(str(path))


def main() -> None:
    OUT.mkdir(exist_ok=True)
    make_contract(OUT / "Договор на ремонт.pdf")
    make_returns(OUT / "Регламент возвратов.docx")
    (OUT / "Памятка приёмщику.txt").write_text(MEMO, encoding="utf-8")
    for p in sorted(OUT.iterdir()):
        print(p)


if __name__ == "__main__":
    main()
